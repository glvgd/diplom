from django.core.management.base import BaseCommand
from holland_test.models import HollandQuestion

class Command(BaseCommand):
    help = 'Загружает вопросы для теста Голланда'

    def handle(self, *args, **options):
        questions_data = [
            # Реалистичный тип (R) - вопросы 1-4
            ("Мне нравится работать с инструментами и техникой", 'R'),
            ("Я предпочитаю физический труд умственному", 'R'),
            ("Мне интересно ремонтировать и собирать механизмы", 'R'),
            ("Я люблю работать на открытом воздухе", 'R'),
            # Интеллектуальный тип (I) - вопросы 5-8
            ("Мне нравится решать сложные задачи и головоломки", 'I'),
            ("Я люблю проводить эксперименты и исследования", 'I'),
            ("Мне интересно изучать научные теории", 'I'),
            ("Я предпочитаю работать с идеями, а не с людьми", 'I'),
            # Артистичный тип (A) - вопросы 9-12
            ("Я творческий человек и люблю самовыражаться", 'A'),
            ("Мне нравится заниматься искусством", 'A'),
            ("Я ценю красоту и гармонию во всем", 'A'),
            ("Мне нравится создавать что-то новое и уникальное", 'A'),
            # Социальный тип (S) - вопросы 13-16
            ("Мне нравится помогать другим людям", 'S'),
            ("Я хороший слушатель и эмпатичный человек", 'S'),
            ("Мне нравится работать в команде", 'S'),
            ("Я получаю удовольствие от обучения других", 'S'),
            # Предприимчивый тип (E) - вопросы 17-20
            ("Я люблю руководить и организовывать людей", 'E'),
            ("Мне нравится убеждать и влиять на других", 'E'),
            ("Я готов рисковать ради достижения целей", 'E'),
            ("Меня привлекает бизнес и предпринимательство", 'E'),
            # Конвенциональный тип (C) - вопросы 21-24
            ("Я аккуратный и организованный человек", 'C'),
            ("Мне нравится работать с данными и документами", 'C'),
            ("Я предпочитаю четкие инструкции", 'C'),
            ("Я люблю порядок и структуру во всем", 'C'),
        ]
        
        for order, (text, p_type) in enumerate(questions_data, start=1):
            obj, created = HollandQuestion.objects.get_or_create(
                order=order,
                defaults={
                    'text': text,
                    'personality_type': p_type
                }
            )
            if created:
                self.stdout.write(f"✓ Создан вопрос {order}")
            else:
                self.stdout.write(f"• Вопрос {order} уже существует")
        
        self.stdout.write(
            self.style.SUCCESS(f'\n✅ Успешно загружено {len(questions_data)} вопросов!')
        )